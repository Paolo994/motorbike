-- Notifiche in-app (foto approvate/rifiutate, nuovi articoli sui topic seguiti, ...)
CREATE TABLE notifications (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    type       VARCHAR(30)   NOT NULL,
    title      VARCHAR(200)  NOT NULL,
    body       VARCHAR(1000),
    link       VARCHAR(500),
    created_at TIMESTAMPTZ   NOT NULL DEFAULT now(),
    read_at    TIMESTAMPTZ
);

CREATE INDEX ix_notifications_user ON notifications (user_id, id DESC);
CREATE INDEX ix_notifications_unread ON notifications (user_id) WHERE read_at IS NULL;

-- Foto profilo: caricate dall'utente, visibili agli altri solo dopo l'approvazione di un admin.
-- L'immagine è ri-codificata dal server (JPEG 400x400): niente metadati EXIF/GPS, niente file malevoli.
CREATE TABLE profile_photos (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    status           VARCHAR(20)  NOT NULL,
    content_type     VARCHAR(50)  NOT NULL,
    data             BYTEA        NOT NULL,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    reviewed_at      TIMESTAMPTZ,
    reviewed_by_id   BIGINT REFERENCES users (id) ON DELETE SET NULL,
    rejection_reason VARCHAR(300),
    CONSTRAINT ck_profile_photos_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED'))
);

-- al massimo una foto in attesa per utente
CREATE UNIQUE INDEX ux_profile_photos_pending ON profile_photos (user_id) WHERE status = 'PENDING';
CREATE INDEX ix_profile_photos_status ON profile_photos (status, created_at);

-- foto approvata attualmente in uso
ALTER TABLE users ADD COLUMN photo_id BIGINT REFERENCES profile_photos (id) ON DELETE SET NULL;
