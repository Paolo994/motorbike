CREATE TABLE friendships (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_id BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    addressee_id BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    status       VARCHAR(20) NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    responded_at TIMESTAMPTZ,
    CONSTRAINT ck_friendships_not_self CHECK (requester_id <> addressee_id),
    CONSTRAINT ck_friendships_status CHECK (status IN ('PENDING', 'ACCEPTED'))
);

-- al massimo una relazione per coppia, indipendentemente da chi ha inviato la richiesta
CREATE UNIQUE INDEX ux_friendships_pair
    ON friendships (LEAST(requester_id, addressee_id), GREATEST(requester_id, addressee_id));

CREATE INDEX ix_friendships_addressee_status ON friendships (addressee_id, status);
CREATE INDEX ix_friendships_requester_status ON friendships (requester_id, status);

-- ricerca utenti per sottostringa dello username (LIKE '%...%')
CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE INDEX ix_users_username_trgm ON users USING gin (lower(username) gin_trgm_ops);
