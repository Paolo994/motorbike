-- Cluster delle notizie. keywords: parole/frasi separate da virgola usate dal classificatore.
CREATE TABLE news_topics (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug        VARCHAR(40)   NOT NULL UNIQUE,
    name        VARCHAR(80)   NOT NULL,
    description VARCHAR(300),
    icon        VARCHAR(40)   NOT NULL DEFAULT 'bi-newspaper',
    sort_order  INT           NOT NULL DEFAULT 0,
    keywords    VARCHAR(4000) NOT NULL DEFAULT ''
);

CREATE TABLE news_sources (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(120) NOT NULL,
    feed_url         VARCHAR(500) NOT NULL UNIQUE,
    site_url         VARCHAR(500),
    language         VARCHAR(5)   NOT NULL DEFAULT 'it',
    default_topic_id BIGINT REFERENCES news_topics (id) ON DELETE SET NULL,
    enabled          BOOLEAN      NOT NULL DEFAULT TRUE,
    last_fetched_at  TIMESTAMPTZ,
    last_status      VARCHAR(20),
    last_error       VARCHAR(500),
    last_new_count   INT,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE news_articles (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id    BIGINT        NOT NULL REFERENCES news_sources (id) ON DELETE CASCADE,
    topic_id     BIGINT        NOT NULL REFERENCES news_topics (id),
    title        VARCHAR(300)  NOT NULL,
    url          VARCHAR(1000) NOT NULL UNIQUE,
    summary      VARCHAR(600),
    image_url    VARCHAR(1000),
    published_at TIMESTAMPTZ   NOT NULL,
    fetched_at   TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE INDEX ix_news_articles_published ON news_articles (published_at DESC);
CREATE INDEX ix_news_articles_topic_published ON news_articles (topic_id, published_at DESC);

-- Topic seguiti: notifica in-app sempre, email opzionale
CREATE TABLE topic_subscriptions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    topic_id      BIGINT      NOT NULL REFERENCES news_topics (id) ON DELETE CASCADE,
    email_enabled BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ux_topic_subscriptions UNIQUE (user_id, topic_id)
);

CREATE INDEX ix_topic_subscriptions_topic ON topic_subscriptions (topic_id);

