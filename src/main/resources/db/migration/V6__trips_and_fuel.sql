-- ---------------------------------------------------------------- carburante (open data MIMIT)

CREATE TABLE fuel_stations (
    id               BIGINT PRIMARY KEY,               -- idImpianto MIMIT
    name             VARCHAR(200),
    brand            VARCHAR(100),
    address          VARCHAR(300),
    comune           VARCHAR(100),
    provincia        VARCHAR(5),
    lat              DOUBLE PRECISION NOT NULL,
    lon              DOUBLE PRECISION NOT NULL,
    petrol_self      NUMERIC(5, 3),                    -- €/l benzina self service
    petrol_served    NUMERIC(5, 3),                    -- €/l benzina servito
    price_updated_at TIMESTAMPTZ,
    imported_at      TIMESTAMPTZ NOT NULL
);

CREATE INDEX ix_fuel_stations_lat_lon ON fuel_stations (lat, lon);

CREATE TABLE fuel_import_runs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at  TIMESTAMPTZ NOT NULL,
    finished_at TIMESTAMPTZ,
    status      VARCHAR(20) NOT NULL,
    stations    INT,
    prices      INT,
    error       VARCHAR(500)
);

-- ---------------------------------------------------------------- road trip

CREATE TABLE trips (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    title       VARCHAR(120) NOT NULL,
    description VARCHAR(2000),
    start_date  DATE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE trip_members (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id    BIGINT      NOT NULL REFERENCES trips (id) ON DELETE CASCADE,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    role       VARCHAR(10) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ux_trip_members UNIQUE (trip_id, user_id),
    CONSTRAINT ck_trip_members_role CHECK (role IN ('OWNER', 'EDITOR', 'VIEWER'))
);

CREATE INDEX ix_trip_members_user ON trip_members (user_id);

CREATE TABLE trip_stages (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id               BIGINT           NOT NULL REFERENCES trips (id) ON DELETE CASCADE,
    position              INT              NOT NULL,
    title                 VARCHAR(120)     NOT NULL,
    stage_date            DATE,
    start_name            VARCHAR(200)     NOT NULL,
    start_lat             DOUBLE PRECISION NOT NULL,
    start_lon             DOUBLE PRECISION NOT NULL,
    end_name              VARCHAR(200)     NOT NULL,
    end_lat               DOUBLE PRECISION NOT NULL,
    end_lon               DOUBLE PRECISION NOT NULL,
    avoid_motorways       BOOLEAN          NOT NULL DEFAULT FALSE,
    avoid_tolls           BOOLEAN          NOT NULL DEFAULT FALSE,
    -- percorso calcolato (Valhalla, profilo moto) o stimato in linea d'aria se il routing non risponde
    route_status          VARCHAR(20)      NOT NULL DEFAULT 'PENDING',
    distance_m            INT,
    duration_s            INT,
    has_motorway          BOOLEAN,
    has_toll              BOOLEAN,
    route_shape           TEXT,                        -- polyline codificata (precisione 6)
    directions_json       TEXT,                        -- [{"text": "...", "km": 1.2}, ...]
    notes                 VARCHAR(4000),               -- indicazioni dettagliate scritte dai partecipanti
    highlights            VARCHAR(4000),               -- cosa vedere
    accommodation_type    VARCHAR(20),
    accommodation_name    VARCHAR(150),
    accommodation_address VARCHAR(250),
    accommodation_price   NUMERIC(8, 2),
    accommodation_url     VARCHAR(500),
    created_at            TIMESTAMPTZ      NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ      NOT NULL DEFAULT now(),
    CONSTRAINT ck_trip_stages_route_status CHECK (route_status IN ('PENDING', 'OK', 'ESTIMATED'))
);

CREATE INDEX ix_trip_stages_trip ON trip_stages (trip_id, position);

CREATE TABLE trip_stops (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage_id BIGINT           NOT NULL REFERENCES trip_stages (id) ON DELETE CASCADE,
    position INT              NOT NULL,
    name     VARCHAR(150)     NOT NULL,
    type     VARCHAR(20)      NOT NULL,
    lat      DOUBLE PRECISION NOT NULL,
    lon      DOUBLE PRECISION NOT NULL,
    notes    VARCHAR(500)
);

CREATE INDEX ix_trip_stops_stage ON trip_stops (stage_id, position);
