-- Conversazioni: DIRECT (1 a 1 tra amici). Il tipo GROUP è previsto per le chat dei road trip.
CREATE TABLE conversations (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type            VARCHAR(20) NOT NULL,
    -- per le DIRECT: "<idMinore>:<idMaggiore>", garantisce una sola conversazione per coppia
    direct_key      VARCHAR(41) UNIQUE,
    title           VARCHAR(120),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_message_at TIMESTAMPTZ,
    CONSTRAINT ck_conversations_type CHECK (type IN ('DIRECT', 'GROUP')),
    CONSTRAINT ck_conversations_direct_key CHECK ((type = 'DIRECT') = (direct_key IS NOT NULL))
);

CREATE TABLE conversation_participants (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id      BIGINT      NOT NULL REFERENCES conversations (id) ON DELETE CASCADE,
    user_id              BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    -- ultimo messaggio letto: i messaggi con id maggiore (scritti da altri) sono "non letti"
    last_read_message_id BIGINT,
    joined_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ux_participants UNIQUE (conversation_id, user_id)
);

CREATE INDEX ix_participants_user ON conversation_participants (user_id);

CREATE TABLE messages (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT        NOT NULL REFERENCES conversations (id) ON DELETE CASCADE,
    sender_id       BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    body            VARCHAR(2000) NOT NULL,
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE INDEX ix_messages_conversation_id ON messages (conversation_id, id DESC);
