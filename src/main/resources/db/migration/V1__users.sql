CREATE TABLE users (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username                  VARCHAR(30)  NOT NULL,
    email                     VARCHAR(254) NOT NULL,
    password_hash             VARCHAR(100) NOT NULL,
    role                      VARCHAR(20)  NOT NULL DEFAULT 'USER',
    enabled                   BOOLEAN      NOT NULL DEFAULT FALSE,
    display_name              VARCHAR(60),
    bio                       VARCHAR(500),
    city                      VARCHAR(80),
    bike_model                VARCHAR(80),
    -- usati dal calcolatore dei costi dei road trip
    fuel_consumption_km_per_l NUMERIC(5, 2),
    tank_capacity_l           NUMERIC(4, 1),
    created_at                TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- username univoco senza distinzione maiuscole/minuscole; l'email è salvata già in minuscolo
CREATE UNIQUE INDEX ux_users_username_lower ON users (lower(username));
CREATE UNIQUE INDEX ux_users_email ON users (email);

CREATE TABLE verification_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token      VARCHAR(64) NOT NULL UNIQUE,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX ix_verification_tokens_user ON verification_tokens (user_id);
